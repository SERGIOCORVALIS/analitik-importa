from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class NichePreset:
    name: str
    section: str
    keywords: str
    wb_path: str
    ozon_path: str
    ru_query: str = ""
    # Rough packed weight; only used for the cargo part of the max purchase price.
    weight_kg: float = 0.3

    @property
    def label(self) -> str:
        return f"{self.section} · {self.name}"

    @property
    def search_ru(self) -> str:
        return self.ru_query or self.name.lower()


def _p(name: str, section: str, en: str, ru: str, wb: str, ozon: str | None = None, kg: float = 0.3) -> NichePreset:
    return NichePreset(name, section, en, wb, ozon or wb, ru, kg)


