def builtin_category_paths(mp: str) -> list[str]:
    paths = {p.ozon_path if mp == "ozon" else p.wb_path for p in NICHE_PRESETS}
    return sorted(paths)


def split_path(path: str) -> tuple[str, str]:
    section, _, rest = path.partition("/")
    return section, rest or section
